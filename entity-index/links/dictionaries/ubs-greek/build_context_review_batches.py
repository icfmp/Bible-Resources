#!/usr/bin/env python3
"""Group original Greek UBS multi-sense exceptions into reviewable context batches.

Input is the private, source-pinned unresolved register generated by
build_provisional_context_sense_overlay.py. No contextual LEXID is inferred,
and the original word IDs, references, candidate lists and annotations are
retained. This output is PRIVATE: it is not a releasable dictionary or index.
"""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

EXPECTED_STATUS = "PRIVATE_UNRESOLVED_Greek_contextual_sense_word_IDs_for_editorial_review"
MULTI = "multiple_original_ubs_lexid_candidates_NOT_contextually_disambiguated"
EXPECTED_MULTI = 2728


def group_for_review(register: dict, batch_size: int = 100) -> dict:
    if batch_size < 1:
        raise ValueError("batch_size must be positive")
    if (register.get("status") != EXPECTED_STATUS
            or register.get("unresolved_original_word_count") != 15237
            or register.get("contextual_senses_independently_verified") != 0
            or register.get("published") is not False
            or register.get("public_release_approved") is not False):
        raise ValueError("Unresolved source evidence register changed")
    source = register.get("word_id_to_unresolved_original_source_evidence")
    if not isinstance(source, dict) or len(source) != 15237:
        raise ValueError("Source original word-ID inventory incomplete")
    families = defaultdict(list)
    counted = 0
    for word_id, word in source.items():
        if word.get("editorial_status") != MULTI:
            continue
        if word.get("original_word_id") != word_id:
            raise ValueError("Original word ID is inconsistent")
        mids = word.get("source_original_ubs_main_id_candidates")
        pairs = word.get("source_ubs_lexid_candidate_pairs")
        if not isinstance(mids, list) or len(mids) != 1 or not isinstance(pairs, list):
            raise ValueError("Invalid source headword/sense evidence")
        if not all(p.get("original_ubs_main_id") == mids[0] and
                   isinstance(p.get("original_ubs_lexid"), str) and
                   p.get("original_ubs_lexid") and
                   p.get("original_ln") in word.get("original_ln", "").split()
                   for p in pairs):
            raise ValueError("Unattested source sense/LN pair")
        candidates = tuple(sorted({p["original_ubs_lexid"] for p in pairs}))
        if len(candidates) < 2:
            raise ValueError("Multiple-sense category lacks multiple UBS LEXIDs")
        lemma = word.get("original_lemma")
        if not isinstance(lemma, str) or not lemma or not word.get("original_reference"):
            raise ValueError("Source lemma/reference missing")
        key = (lemma, mids[0], candidates)
        families[key].append({
            "original_word_id": word_id,
            "original_reference": word["original_reference"],
            "original_lemma": lemma,
            "original_strong": word["original_strong"],
            "original_ln": word["original_ln"],
            "original_class": word["original_class"],
            "original_morph": word["original_morph"],
            "source_ubs_lexid_candidate_pairs": pairs,
            "editorial_contextual_lexid_selection": None,
            "editorial_rationale": None,
            "contextually_verified": False,
        })
        counted += 1
    if counted != EXPECTED_MULTI:
        raise ValueError(f"Expected {EXPECTED_MULTI} multi-LEXID words; got {counted}")
    ordered = sorted(families.items(), key=lambda t: (-len(t[1]), t[0]))
    chunks = []
    for (lemma, mid, candidate_ids), words in ordered:
        words = sorted(words, key=lambda w: w["original_word_id"])
        for start in range(0, len(words), batch_size):
            chunks.append({
                "original_lemma": lemma,
                "ubs_main_id": mid,
                "candidate_ubs_lexids": list(candidate_ids),
                "family_original_word_total": len(words),
                "word_id_evidence": words[start:start + batch_size],
            })
    if sum(len(x["word_id_evidence"]) for x in chunks) != EXPECTED_MULTI:
        raise ValueError("Review batch partition lost original source words")
    return {
        "status": "PRIVATE_Greek_UBS_contextual_review_batches_NO_CHOICES_YET",
        "source_editions": register["source_editions"],
        "original_multi_sense_word_count": counted,
        "review_groups": len(ordered),
        "review_batches": chunks,
        "contextually_verified": 0,
        "source_modified": False,
        "published": False,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--unresolved", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--batch-size", type=int, default=100)
    args = parser.parse_args()
    source = json.loads(args.unresolved.read_text(encoding="utf-8-sig"))
    result = group_for_review(source, args.batch_size)
    args.output.write_text(json.dumps(result, ensure_ascii=False, sort_keys=True,
                                      separators=(",", ":")) + "\n", encoding="utf-8")
    print(json.dumps({"multi_sense_original_words": result["original_multi_sense_word_count"],
                      "groups": result["review_groups"],
                      "batches": len(result["review_batches"]),
                      "contextually_verified": 0, "published": False}, sort_keys=True))


if __name__ == "__main__":
    main()
