#!/usr/bin/env python3
"""Generic fail-closed prose-draft to SHA-pinned native-SWORD source-unit gate.

This only verifies *declared coverage, original section boundaries and chapter
metadata*. It never certifies that the new prose conveys every authorial idea.
It never exports the original commentary text or markup. The original source
native receipt is generated by a separate real stock-SWORD audit.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import unicodedata

_HEX = re.compile(r"^[0-9a-f]{64}$")
_OSIS_CHAPTER = re.compile(r"^[1-4]?[A-Za-z][A-Za-z0-9]*\.[1-9][0-9]{0,2}$")
_FRONT_FIELD = re.compile(r'^([A-Za-z_][A-Za-z0-9_]*): "([^"\r\n]*)"$')
_RANGE = re.compile(r"\bverses\s+(\d{1,3})\s*[-–—]\s*(\d{1,3})", re.I)
_SINGLE = re.compile(r"\bverse\s+(\d{1,3})\b", re.I)
_WORD = re.compile(r"[\w’-]+", re.UNICODE)

_SCOPE_CLAIM = re.compile(r"\\(\\s*verses?\\s+([^)]+)\\)", re.I)
_EXACT_SCOPE_SEGMENT = re.compile(r"(\\d{1,3})(?:\\s*[-–—]\\s*(\\d{1,3}))?")


def _claimed_verse_keys_in_heading(heading: str) -> list[int] | None:
    """Expand explicit parenthesized authorial scopes; do not span source gaps.

    Supports a single verse, a continuous range, or disjoint source ranges
    joined by commas, semicolons or 'and' (e.g. verses 24–30 and 36–43).
    Other source headings are left to the established narrow legacy checks.
    """
    found = _SCOPE_CLAIM.search(heading)
    if not found:
        return None
    # Normalize syntactic separators, not authorial verse addresses.
    scope = re.sub(r"\\s+and\\s+", ",", found[1], flags=re.I)
    parts = [part.strip() for part in re.split(r"[,;]", scope)]
    if not parts or any(not part for part in parts):
        raise ValueError("Malformed modern commentary verse scope")
    claimed = []
    for part in parts:
        match = _EXACT_SCOPE_SEGMENT.fullmatch(part)
        if not match:
            raise ValueError("Unrecognized modern commentary verse scope")
        start = int(match[1])
        end = int(match[2]) if match[2] is not None else start
        if start < 1 or end < start:
            raise ValueError("Reversed/zero modern commentary verse scope")
        claimed.extend(range(start, end + 1))
    if len(set(claimed)) != len(claimed):
        raise ValueError("Duplicated modern commentary verse scope")
    return claimed



def read_chapter_draft(path: Path, *, allow_production_candidate: bool = False) -> dict:
    source = path.read_text(encoding="utf-8")
    if not source.startswith("---\n"):
        raise ValueError("Markdown draft lacks exact front matter: " + path.name)
    marker = source.find("\n---\n", 4)
    if marker < 0:
        raise ValueError("Markdown draft front matter is unterminated")
    fields = {}
    for line in source[4:marker].splitlines():
        if not line.strip():
            continue
        matched = _FRONT_FIELD.fullmatch(line)
        if matched is None or matched[1] in fields:
            raise ValueError("Malformed or duplicate draft front matter: " + path.name)
        fields[matched[1]] = matched[2]
    allowed = {"DRAFT — NOT VALIDATED"}
    if allow_production_candidate:
        allowed.add("PRODUCTION CANDIDATE — NOT VALIDATED")
    if fields.get("status") not in allowed:
        raise ValueError("An unapproved draft cannot claim validated status")
    chapter = fields.get("chapter_osis", "")
    if not _OSIS_CHAPTER.fullmatch(chapter):
        raise ValueError("Missing valid canonical chapter_osis")
    prose = source[marker + len("\n---\n"):]
    end = re.search(r"(?m)^---\s*$", prose)
    if end is None:
        raise ValueError("Missing clear boundary before non-prose review checklist")
    prose = prose[:end.start()]
    heads = list(re.finditer(r"(?m)^## (.+)\s*$", prose))
    if not heads:
        raise ValueError("No original-aligned exposition blocks present")
    units = []
    for i, h in enumerate(heads):
        text = prose[h.end(): heads[i + 1].start() if i + 1 < len(heads) else len(prose)]
        if len(_WORD.findall(text)) < 18:
            raise ValueError("Draft source unit is suspiciously empty: " + path.name)
        if any(char in text for char in ("\x00", "\ufffd")):
            raise ValueError("Malformed Unicode in modern prose")
        units.append({"heading": h[1].strip(), "word_count": len(_WORD.findall(text))})
    if unicodedata.normalize("NFC", prose) != prose:
        raise ValueError("Modern draft prose must be normalized Unicode NFC")
    return {"chapter": chapter, "fields": fields, "sections": units, "path": path}


def verify_draft_against_native_map(draft: dict, native: dict, *,
                                    source_zip_sha256: str,
                                    source_native_sha256: str) -> dict:
    meta = draft["fields"]
    if meta.get("source_zip_sha256") != source_zip_sha256 or not _HEX.fullmatch(source_zip_sha256):
        raise ValueError("Pilot source ZIP pin missing or different")
    if meta.get("source_native_corpus_sha256") != source_native_sha256 or not _HEX.fullmatch(source_native_sha256):
        raise ValueError("Pilot full native corpus pin missing or different")
    expected = native.get("units")
    if not isinstance(expected, list) or not expected:
        raise ValueError("No verified original native section groups for chapter")
    actual = draft["sections"]
    if len(actual) != len(expected):
        raise ValueError("Draft section count does not match published native source")
    anchors = []
    for idx, (editorial, original) in enumerate(zip(actual, expected)):
        native_keys = original.get("native_keys")
        if not isinstance(native_keys, list) or not native_keys:
            raise ValueError("No original occupied keys attached to a source unit")
        nums = []
        prefix = draft["chapter"] + "."
        for key in native_keys:
            if not isinstance(key, str) or not key.startswith(prefix):
                raise ValueError("Source unit references another chapter or invalid key")
            try:
                number = int(key[len(prefix):])
            except ValueError as exc:
                raise ValueError("Malformed source native verse address") from exc
            nums.append(number)
        if len(set(nums)) != len(nums):
            raise ValueError("Duplicate native source verse in unit")
        bounds = (min(nums), max(nums))
        h = editorial["heading"]
        exact_scope = _claimed_verse_keys_in_heading(h)
        rg = _RANGE.search(h)
        sn = _SINGLE.search(h)
        # Parenthesized scopes MUST identify the actual *set and order* of
        # original occupied K keys, including gaps between nonadjacent ranges.
        # A simple min/max comparison could overwrite another source body.
        if exact_scope is not None:
            if exact_scope != nums:
                raise ValueError("Editor heading misstates original range or occupied verse keys: "
                                 + draft["chapter"])
        elif rg is not None:
            claimed = (int(rg[1]), int(rg[2]))
            if claimed != bounds:
                raise ValueError("Editor heading misstates original range: " + draft["chapter"])
        elif sn is not None and (int(sn[1]), int(sn[1])) != bounds:
            raise ValueError("Editor heading misstates original single-verse scope")
        anchors.append({"first_native_key": native_keys[0],
                        "last_native_key": native_keys[-1],
                        "source_raw_sha256": original.get("raw_sha256"),
                        "editorial_heading_range_claim_checked":
                            exact_scope is not None or rg is not None or sn is not None,
                        "draft_exposition_words": editorial["word_count"]})
    return {
        "chapter": draft["chapter"],
        "section_count": len(actual),
        "source_key_count": sum(len(u["native_keys"]) for u in expected),
        "exact_source_unit_anchors": anchors,
        "draft_total_exposition_words": sum(u["word_count"] for u in actual),
        "semantic_source_text_compared": False,
        "approved_or_published": False
    }


def run(root: Path, metadata_path: Path) -> dict:
    ledger = json.loads(metadata_path.read_text(encoding="utf-8"))
    if ledger.get("native_source_integrity_passed") is not True:
        raise ValueError("Native map was not produced from the whole pinned original")
    if ledger.get("semantic_translation_review_approved") is not False:
        raise ValueError("This is an unapproved source-coverage audit")
    if ledger.get("source_full_raw_osis_markup_exported") is not False:
        raise ValueError("Native map unexpectedly contains original raw markup")
    chapters = ledger.get("chapters")
    if not isinstance(chapters, dict) or not chapters:
        raise ValueError("Empty native original chapter evidence")
    files = sorted(root.rglob("*.DRAFT.md"))
    if not files:
        raise ValueError("No modern chapter draft files to verify")
    # Read only front matter to distinguish book-level introductions.
    # Every extra numbered draft must still cause the equality check to fail.
    chapter_files = []
    for f in files:
        header = f.read_text(encoding="utf-8").split("\n---\n", 1)[0]
        if re.search(r"(?m)^chapter_osis: ", header):
            chapter_files.append(f)
    read = [read_chapter_draft(f) for f in chapter_files]
    if len(read) != len(chapters) or {d["chapter"] for d in read} != set(chapters):
        raise ValueError("Draft chapter files and full native receipt have a mismatch or duplicate")
    approved_zip = ledger.get("package_sha256")
    approved_native = ledger.get("whole_native_source_sha256")
    reports = []
    for d in read:
        reports.append(verify_draft_against_native_map(d, chapters[d["chapter"]],
            source_zip_sha256=approved_zip, source_native_sha256=approved_native))
    return {
        "status": "DRAFT_SECTION_AND_METADATA_COVERAGE_ONLY",
        "checked_chapters": len(reports),
        "checked_original_source_raw_groups": sum(r["section_count"] for r in reports),
        "checked_original_native_verse_keys": sum(r["source_key_count"] for r in reports),
        "source_verified_by_native_receipt": True,
        "semantic_translation_review_approved": False,
        "source_osis_reference_markup_preservation_verified": False,
        "derivative_sword_roundtrip_tested": False,
        "chapters": reports
    }


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--root", required=True, type=Path)
    p.add_argument("--native-map", required=True, type=Path)
    p.add_argument("--report", required=True, type=Path)
    a = p.parse_args()
    result = run(a.root, a.native_map)
    a.report.parent.mkdir(parents=True, exist_ok=True)
    a.report.write_text(json.dumps(result, sort_keys=True, indent=2) + "\n", encoding="utf-8")
    print("Draft-to-exact-native coverage PASS: "
          + str(result["checked_chapters"]) + " chapters; "
          + str(result["checked_original_source_raw_groups"]) + " source groups; "
          + str(result["checked_original_native_verse_keys"]) + " original native keys; "
          "not independently semantically approved")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
